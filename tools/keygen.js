#!/usr/bin/env node
// Creates the Ed25519 key pair that signs licenses and the app's downloadable resources.
//
//   npm run keys                      create keys/license-private.pem and src/public-key.js
//   npm run keys -- --worker-secret   print the private key in the form the license server wants:
//                                     npm run -s keys -- --worker-secret | npx wrangler secret put LICENSE_PRIVATE_KEY
//
// The private key never leaves your computer except as that server secret. Back it up:
// without it you can't issue licenses that already-installed copies accept.
import { createPublicKey, generateKeyPairSync } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { PRIVATE_KEY_FILE, ROOT, loadPrivateKey } from './lib/sign.js';

const { values } = parseArgs({ options: { force: { type: 'boolean' }, 'worker-secret': { type: 'boolean' } } });
const PUBLIC_KEY_FILE = path.join(ROOT, 'src', 'public-key.js');

if (values['worker-secret']) {
  process.stdout.write(loadPrivateKey().export({ format: 'der', type: 'pkcs8' }).toString('base64'));
  process.exit(0);
}

if (existsSync(PRIVATE_KEY_FILE) && !values.force) {
  console.error(`A key already exists (${path.relative(ROOT, PRIVATE_KEY_FILE)}).
Replacing it makes every license you have already sold stop working, and installed
copies would need a new build. If you really mean it: npm run keys -- --force`);
  process.exit(1);
}

const { privateKey } = generateKeyPairSync('ed25519');
mkdirSync(path.dirname(PRIVATE_KEY_FILE), { recursive: true });
writeFileSync(PRIVATE_KEY_FILE, privateKey.export({ format: 'pem', type: 'pkcs8' }), { mode: 0o600 });
writePublicKey(createPublicKey(privateKey).export({ format: 'der', type: 'spki' }).toString('base64'));

console.log(`Created ${path.relative(ROOT, PRIVATE_KEY_FILE)} (secret - back it up, never commit it)
and ${path.relative(ROOT, PUBLIC_KEY_FILE)} (built into the app).
Next: give the license server the private key:
  npm run -s keys -- --worker-secret | npx wrangler secret put LICENSE_PRIVATE_KEY --config server/wrangler.toml`);

function writePublicKey(spki) {
  writeFileSync(
    PUBLIC_KEY_FILE,
    `// Generated by "npm run keys". The app checks license signatures against this key;
// the matching private key is keys/license-private.pem (never shipped).
export const PUBLIC_KEY = '${spki}';
`,
  );
}
